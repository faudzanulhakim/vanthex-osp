def format_date(lang, tm):
    """Tanggal laporan terlokalisasi (nama bulan + urutan per bahasa)."""
    lang = norm_lang(lang)
    d, m, y = tm.tm_mday, tm.tm_mon, tm.tm_year
    if lang == "ja":
        return f"{y}年{m}月{d}日"
    if lang == "zh":
        return f"{y}年{m}月{d}日"
    if lang == "ko":
        return f"{y}년 {m}월 {d}일"
    mon = _MONTHS[lang][m - 1]
    if lang == "de":
        return f"{d}. {mon} {y}"
    if lang == "en":
        return f"{d:02d} {mon} {y}"  # identik format lama strftime("%d %B %Y")
    return f"{d} {mon} {y}"


