LANGS = ("en", "id", "es", "fr", "de", "pt", "ru", "ja", "ko", "zh", "ar", "hi")


def norm_lang(lang):
    """Normalisasi kode bahasa request -> salah satu dari LANGS."""
    code = str(lang or "").strip().lower().replace("_", "-").split("-")[0]
    return code if code in LANGS else "en"


def t(lang, key, **kw):
    """Ambil string kerangka `key` dalam `lang` (fallback per-kunci ke en)."""
    lang = norm_lang(lang)
    s = T.get(lang, {}).get(key)
    if s is None:
        s = T["en"][key]
    return s.format(**kw) if kw else s


