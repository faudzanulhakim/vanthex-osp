"""Test deteksi WAF (v3.4.1) — regresi insiden FP F5 pada aplikasi GeneXus.

Kasus nyata 2026-10-16: target nginx + aplikasi GeneXus dituduh "F5 BIG-IP"
karena pola lama r"f5" cocok dengan substring di token hex acak
(gx_ajax_key "38ff6460ffff59ff..."). Signature kini indikator kuat per vendor,
terpisah header/body, dan evidence mencatat indikator yang cocok.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from vulnscan2 import _waf_behavior_verdict, _waf_match

GENEXUS_BODY = ('<script>var GX = {"gx_ajax_key":"38ff6460ffff59ffff06ff6bffff3644",'
                '"gx_ajax_iv":"8722e2ea52fd44f599d35d1534485d8e",'
                '"ajax_security_token":"0d34f2c8d3f5aa19"};</script>'
                '<footer>Powered by nginx — blog membahas akamai, barracuda, f5.</footer>')


def test_genexus_hex_tokens_bukan_f5():
    hit = _waf_match([("Server", "nginx"), ("Content-Type", "text/html")], GENEXUS_BODY)
    assert hit is None, f"FP WAF pada token hex GeneXus: {hit}"


def test_amzn_trace_bukan_aws_waf():
    hit = _waf_match([("X-Amzn-Trace-Id", "Root=1-6789f5ab-cdef0123456789")],
                     "<html>app biasa</html>")
    assert hit is None, f"x-amzn-trace-id (ALB) bukan bukti WAF: {hit}"


def test_f5_dari_cookie_bigipserver():
    hit = _waf_match([("Set-Cookie", "BIGipServerAppPool=rd5o00000000000000000000ffff; path=/")], "")
    assert hit and hit[0] == "F5 BIG-IP" and "header" in hit[1]


def test_f5_dari_cookie_asm_ts():
    hit = _waf_match([("Set-Cookie", "TS01429a8c=028e2f31b2c4; Path=/")], "")
    assert hit and hit[0] == "F5 BIG-IP"


def test_cloudflare_dari_cf_ray():
    hit = _waf_match([("CF-RAY", "8f00abcd-SIN"), ("Server", "cloudflare")], "")
    assert hit and hit[0] == "Cloudflare"


def test_cloudflare_dari_body_block_page():
    hit = _waf_match([("Server", "nginx")],
                     "<title>Attention Required! | Cloudflare</title>Sorry, you have been blocked")
    assert hit and hit[0] == "Cloudflare"


def test_akamai_butuh_indikator_kuat():
    assert _waf_match([("Server", "nginx")], "kami memakai akamai untuk cdn gambar") is None
    hit = _waf_match([("X-Akamai-Transformed", "9 - 0 pmb=mRUM,3")], "")
    assert hit and hit[0] == "Akamai"


def test_modsecurity_dari_body():
    hit = _waf_match([], "This error was generated by Mod_Security.")
    assert hit and hit[0] == "ModSecurity"


# ---------- v3.5: verdict perilaku (bukan tebakan signature) ----------

def _p(kind, status, body=""):
    return {"kind": kind, "status": status, "body": body}


def test_perilaku_terkonfirmasi_saat_serangan_diblokir_kontrol_lolos():
    probes = [_p("attack", 403), _p("attack", 403), _p("attack", 404),
              _p("control", 404), _p("control", 200), _p("control", 404)]
    v = _waf_behavior_verdict(probes)
    assert v["confirmed"] and v["blocked_attacks"] == 2 and v["blocked_controls"] == 0


def test_perilaku_tidak_terkonfirmasi_saat_kontrol_ikut_diblokir():
    # Server yang memblokir SEMUA request ke path asing (rate/IP policy)
    # bukan bukti WAF — kontrol ikut terblokir.
    probes = [_p("attack", 403), _p("attack", 403), _p("attack", 403),
              _p("control", 403), _p("control", 404), _p("control", 404)]
    assert not _waf_behavior_verdict(probes)["confirmed"]


def test_perilaku_tidak_terkonfirmasi_saat_tidak_ada_blocking():
    probes = [_p("attack", 404), _p("attack", 200), _p("attack", 404),
              _p("control", 404), _p("control", 404), _p("control", 200)]
    assert not _waf_behavior_verdict(probes)["confirmed"]


def test_perilaku_satu_blocking_saja_belum_cukup():
    probes = [_p("attack", 403), _p("attack", 404), _p("attack", 404),
              _p("control", 404), _p("control", 404), _p("control", 404)]
    assert not _waf_behavior_verdict(probes)["confirmed"]
