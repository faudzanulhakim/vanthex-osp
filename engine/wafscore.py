GENERIC_BLOCK_PHRASES = [
    r"you have been blocked", r"request blocked", r"access denied",
    r"blocked by.{0,30}(security|firewall|waf)", r"security policy",
    r"this request was blocked", r"bot management", r"are you a robot",
    r"checking your browser",
]

_HDR = [(re.compile(p, re.I), v, s, lbl) for p, v, s, lbl in HEADER_RULES]
_BDY = [(re.compile(p, re.I), v, s, lbl) for p, v, s, lbl in BODY_RULES]
_GEN = [re.compile(p, re.I) for p in GENERIC_BLOCK_PHRASES]


def _header_blob(headers):
    parts = []
    for h in headers or []:
        if isinstance(h, (list, tuple)) and len(h) >= 2:
            parts.append(f"{h[0]}: {h[1]}")
        else:
            parts.append(str(h))
    return "; ".join(parts).lower()


def score_waf(headers, body, status=None):
    """Score all vendor candidates for one response.

    Returns {"vendors": [{vendor, score, signals: [label, ...]}]
             sorted by score desc (only vendors with >= 1 signal),
             "generic_block": bool}"""
    blob = _header_blob(headers)
    text = (body or "")[:120000]
    per = {}

    def hit(vendor, score, label, scope):
        cur = per.setdefault(vendor, {"vendor": vendor, "score": 0.0,
                                      "signals": []})
        cur["score"] = max(cur["score"], score)
        cur["signals"].append(f"{scope} ~ '{label}' ({score:.2f})")

    for pat, vendor, score, label in _HDR:
        if pat.search(blob):
            hit(vendor, score, label, "header")
    low = text.lower()
    for pat, vendor, score, label in _BDY:
        if pat.search(low):
            hit(vendor, score, label, "body")
    boost = 0.0
    if status in BLOCK_STATUSES:
        boost = STATUS_BOOST
    vendors = []
    for v in per.values():
        if boost:
            v = dict(v)
            v["score"] = min(1.0, v["score"] + boost)
            v["signals"].append(f"blocking status {status} (+0.05)")
        vendors.append(v)
    vendors.sort(key=lambda x: -x["score"])
    return {"vendors": vendors,
            "generic_block": any(p.search(low) for p in _GEN)}


def merge_scored(*scored):
    """Max-merge several score_waf results (e.g. home page + blocked
    provocation responses). Signals concatenate (deduped, capped)."""
    per = {}
    generic = False
    for s in scored:
        if not s:
            continue
        generic = generic or bool(s.get("generic_block"))
        for v in s.get("vendors", []):
            cur = per.setdefault(v["vendor"], {"vendor": v["vendor"],
                                               "score": 0.0, "signals": []})
            cur["score"] = max(cur["score"], v["score"])
            for sig in v["signals"]:
                if sig not in cur["signals"]:
                    cur["signals"].append(sig)
    out = sorted(per.values(), key=lambda x: -x["score"])
    for v in out:
        v["signals"] = v["signals"][:6]
    return {"vendors": out, "generic_block": generic}


def best_vendor(scored, floor=DISPLAY_FLOOR):
    """Top vendor at/above the display floor, else None."""
    for v in (scored or {}).get("vendors", []):
        if v["score"] >= floor:
            return v
    return None


def evidence_str(v):
    """Finding-evidence rendering: score + constituent signals are
    mandatory (design WS3) so the claim can be audited."""
    return (f"{v['vendor']} score {v['score']:.2f} — signals: "
            + "; ".join(v["signals"]))


def match(headers, body, status=None):
    """Backward-compatible _waf_match shape: (vendor, evidence) for
    the best vendor at/above the floor, else None. The evidence leads
    with the scope of the strongest signal ('header …' / 'body …')
    like the legacy format, then the full scored breakdown."""
    scored = score_waf(headers, body, status=status)
    v = best_vendor(scored)
    if not v:
        return None
    lead = v["signals"][0] if v["signals"] else ""
    scope = lead.split(" ", 1)[0] if lead else ""
    return v["vendor"], f"{scope} signal — " + evidence_str(v)
